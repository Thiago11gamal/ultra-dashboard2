import React, { useState, useMemo } from 'react';
import { useNavigate } from 'react-router-dom';
import { useAppStore } from '../store/useAppStore';
import { useToast } from '../hooks/useToast';
import { Calendar, Plus, Trash2, Clock, Target, ChevronLeft, ChevronRight, Sparkles, RefreshCw, Play, CheckCircle2, BrainCircuit } from 'lucide-react';
import { format, addMonths, subMonths, startOfMonth, endOfMonth, eachDayOfInterval, isSameDay, isToday, addDays } from 'date-fns';
import { ptBR } from 'date-fns/locale';
import { generateId } from '../utils/idGenerator';
import { getDateKey, parseNoonLocal, normalizeDate } from '../utils/dateHelper';
import { isSubjectMatch, normalize } from '../utils/normalization';
import { parseCoachTask, isSystemAlertTask } from '../utils/coachText';
import { PageErrorBoundary } from '../components/ErrorBoundary';
import ConfirmModal from '../components/ConfirmModal';
import { generateOptimalWeeklySchedule, rebalanceRemainingWeekSchedule } from '../engine/adaptive/allocationOptimizer';
import { reconcileContestCategoriesHistory, isRealSimuladoRow } from '../utils/simuladoReconciler';
import { isSubjectAlreadyActiveInPomodoro } from '../utils/pomodoroHelpers';

const EMPTY_ARRAY = Object.freeze([]);

function getActiveContest(state) {
  const id = state.appState?.activeId || 'default';
  return state.appState?.contests?.[id] || {};
}

export default function Agenda() {
  const navigate = useNavigate();
  const activeId = useAppStore(state => state.appState?.activeId || 'default');
  const rawAgenda = useAppStore(state => getActiveContest(state).agenda || EMPTY_ARRAY);
  const agenda = useMemo(() => (Array.isArray(rawAgenda) ? rawAgenda : Object.values(rawAgenda || {})).filter(Boolean), [rawAgenda]);
  const rawCoachPlanner = useAppStore(state => getActiveContest(state).coachPlanner || null);
  const rawCategories = useAppStore(state => getActiveContest(state).categories || EMPTY_ARRAY);
  const categories = useMemo(() => (Array.isArray(rawCategories) ? rawCategories : Object.values(rawCategories || {})).filter(Boolean), [rawCategories]);
  const rawStudyLogs = useAppStore(state => getActiveContest(state).studyLogs || EMPTY_ARRAY);
  const studyLogs = useMemo(() => (Array.isArray(rawStudyLogs) ? rawStudyLogs : Object.values(rawStudyLogs || {})).filter(Boolean), [rawStudyLogs]);
  const rawStudySessions = useAppStore(state => getActiveContest(state).studySessions || EMPTY_ARRAY);
  const studySessions = useMemo(() => (Array.isArray(rawStudySessions) ? rawStudySessions : Object.values(rawStudySessions || {})).filter(Boolean), [rawStudySessions]);
  const rawSimuladoRows = useAppStore(state => getActiveContest(state).simuladoRows || EMPTY_ARRAY);
  const simuladoRows = useMemo(() => (Array.isArray(rawSimuladoRows) ? rawSimuladoRows : Object.values(rawSimuladoRows || {})).filter(Boolean), [rawSimuladoRows]);
  const contestMaxScore = useAppStore(state => getActiveContest(state).maxScore ?? 100);
  const contestMinScore = useAppStore(state => getActiveContest(state).minScore ?? 0);
  const contestPenalty = useAppStore(state => getActiveContest(state).penaltyPerWrong ?? 0);
  const reconciledCategories = useMemo(() => {
    if (!categories.length || !simuladoRows.some(isRealSimuladoRow)) return categories;
    return reconcileContestCategoriesHistory(categories, simuladoRows, contestMaxScore, contestMinScore, { penaltyPerWrong: contestPenalty });
  }, [categories, simuladoRows, contestMaxScore, contestMinScore, contestPenalty]);
  const setData = useAppStore(state => state.setData);
  const startPomodoroSession = useAppStore(state => state.startPomodoroSession);
  const showToast = useToast();

  const [eventToDelete, setEventToDelete] = useState(null);
  const [showAutoModal, setShowAutoModal] = useState(false);
  const [dailyHours, setDailyHours] = useState([2, 3, 3, 3, 3, 3, 4]);

  const optimalPreview = useMemo(() => {
    if (!showAutoModal) return null;
    return generateOptimalWeeklySchedule(reconciledCategories, studyLogs, studySessions, simuladoRows, { dailyHours });
  }, [showAutoModal, reconciledCategories, studyLogs, studySessions, simuladoRows, dailyHours]);

  const applyOptimalSchedule = () => {
    if (!optimalPreview?.events?.length) {
      showToast('Cadastre ao menos 1 disciplina para gerar a grade ótima.', 'warning');
      return;
    }
    const removedIds = agenda.filter((ev) => ev && ev.autoGenerated && ev.id).map((ev) => ev.id);
    const next = [...agenda.filter((ev) => !ev.autoGenerated), ...optimalPreview.events];
    persistAgenda(next, removedIds);
    setShowAutoModal(false);
    showToast(`${optimalPreview.events.length} blocos otimizados aplicados à Agenda!`, 'success');
  };

  const handleRebalanceRemainingWeek = () => {
    if (!reconciledCategories.length) {
      showToast('Cadastre ao menos 1 disciplina para rebalancear a semana.', 'warning');
      return;
    }
    const res = rebalanceRemainingWeekSchedule(agenda, reconciledCategories, studyLogs, studySessions, simuladoRows, { dailyHours });
    if (!res.addedCount) {
      showToast('Nenhum bloco pendente para rebalancear hoje.', 'info');
      return;
    }
    const nextIds = new Set((res.events || []).map((ev) => ev?.id).filter(Boolean));
    const removedIds = agenda.filter((ev) => ev && ev.id && !nextIds.has(ev.id)).map((ev) => ev.id);
    persistAgenda(res.events, removedIds);
    showToast(
      `Semana rebalanceada: ${res.addedCount} blocos redistribuídos nos próximos ${res.daysRemaining} dia(s)${res.missedBlocksDetected > 0 ? ` (${res.missedBlocksDetected} perdido(s) compensado(s))` : ''}!`,
      'success'
    );
  };

  // Sincronização Coach IA -> Agenda: importa os cards das colunas mon..sun do Kanban do Coach para os dias da semana atual
  const handleSyncFromCoachPlanner = () => {
    if (!rawCoachPlanner || typeof rawCoachPlanner !== 'object') {
      showToast('Abra o Coach IA primeiro para gerar ou organizar seu Planner semanal.', 'info');
      return;
    }
    const dayKeyByJsDay = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];
    const baseToday = getTodayAlignedDate();
    const todayStr = format(baseToday, 'yyyy-MM-dd');
    const currentJsDay = baseToday.getDay();
    const mondayOffset = currentJsDay === 0 ? -6 : 1 - currentJsDay;
    const weekMonday = addDays(baseToday, mondayOffset);

    const plannerCompletionById = new Map();
    const plannerCompletionBySig = new Map();
    const orderedKeys = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun'];

    orderedKeys.forEach((colKey) => {
      const rawTasks = Array.isArray(rawCoachPlanner[colKey])
        ? rawCoachPlanner[colKey]
        : Object.values(rawCoachPlanner[colKey] || {});
      rawTasks.filter((t) => t && !isSystemAlertTask(t)).forEach((task) => {
        if (task.id) plannerCompletionById.set(String(task.id), Boolean(task.completed));
        const parsed = parseCoachTask(task, categories);
        const subjectName = parsed.subjectRaw || task.category || task.catName || categories[0]?.name || 'Geral';
        const matchedCat = categories.find((c) => c && isSubjectMatch(subjectName, c.name));
        const title = parsed.topic || task.topicName || task.title || task.text || 'Missão do Coach';
        plannerCompletionBySig.set(`${normalize(title)}|${normalize(matchedCat?.name || subjectName)}`, Boolean(task.completed));
      });
    });

    let updatedExistingCount = 0;
    const nowIso = new Date().toISOString();
    const syncedExistingAgenda = agenda.map((ev) => {
      if (!ev || !ev.coachSynced) return ev;
      const sigKey = `${normalize(ev.title || '')}|${normalize(ev.subject || '')}`;
      const nextDone = ev.coachPlannerTaskId && plannerCompletionById.has(String(ev.coachPlannerTaskId))
        ? plannerCompletionById.get(String(ev.coachPlannerTaskId))
        : plannerCompletionBySig.get(sigKey);
      if (typeof nextDone === 'boolean' && Boolean(ev.completed) !== nextDone) {
        updatedExistingCount += 1;
        return {
          ...ev,
          completed: nextDone,
          completedAt: nextDone ? (ev.completedAt || nowIso) : null,
          ...(nextDone ? {} : { manuallyUnchecked: true }),
        };
      }
      return ev;
    });

    const existingCoachIds = new Set(
      syncedExistingAgenda.map((ev) => (ev?.coachPlannerTaskId ? String(ev.coachPlannerTaskId) : null)).filter(Boolean)
    );
    const existingCoachSigs = new Set(
      syncedExistingAgenda.map((ev) => `${ev?.date || ''}|${normalize(ev?.title || '')}|${normalize(ev?.subject || '')}`)
    );
    const imported = [];

    orderedKeys.forEach((colKey, colIdx) => {
      const targetDate = addDays(weekMonday, colIdx);
      const rawDateStr = format(targetDate, 'yyyy-MM-dd');
      const rawTasks = Array.isArray(rawCoachPlanner[colKey])
        ? rawCoachPlanner[colKey]
        : Object.values(rawCoachPlanner[colKey] || {});
      rawTasks.filter((t) => t && !isSystemAlertTask(t)).forEach((task, idx) => {
        if (task.id && existingCoachIds.has(String(task.id))) return;
        const parsed = parseCoachTask(task, categories);
        const subjectName = parsed.subjectRaw || task.category || task.catName || categories[0]?.name || 'Geral';
        const matchedCat = categories.find((c) => c && isSubjectMatch(subjectName, c.name));
        const title = parsed.topic || task.topicName || task.title || task.text || 'Missão do Coach';
        // Evita criar blocos pendentes já vencidos em dias passados da semana atual
        const effectiveDateStr = rawDateStr < todayStr && !task.completed ? todayStr : rawDateStr;
        const sig = `${effectiveDateStr}|${normalize(title)}|${normalize(matchedCat?.name || subjectName)}`;
        const origSig = `${rawDateStr}|${normalize(title)}|${normalize(matchedCat?.name || subjectName)}`;
        if (existingCoachSigs.has(sig) || existingCoachSigs.has(origSig)) return;
        existingCoachSigs.add(sig);
        if (task.id) existingCoachIds.add(String(task.id));
        const slotHour = String(Math.min(21, 8 + idx * 2)).padStart(2, '0');
        imported.push({
          id: generateId('agenda'),
          date: effectiveDateStr,
          time: `${slotHour}:00`,
          title,
          subject: matchedCat?.name || subjectName,
          ...(matchedCat?.id ? { categoryId: matchedCat.id } : {}),
          ...(task.sourceTaskId ? { taskId: task.sourceTaskId } : {}),
          ...(task.id ? { coachPlannerTaskId: String(task.id) } : {}),
          duration: Number(task.estimatedMinutes || task.minutes) || 60,
          completed: Boolean(task.completed),
          coachSynced: true,
          notes: parsed.action || 'Sincronizado do Kanban Semanal do Coach IA',
          createdAt: nowIso,
        });
      });
    });

    if (imported.length === 0 && updatedExistingCount === 0) {
      const hasAnyInPlanner = dayKeyByJsDay.some((k) => {
        const list = Array.isArray(rawCoachPlanner[k]) ? rawCoachPlanner[k] : Object.values(rawCoachPlanner[k] || {});
        return list.some((t) => t && !isSystemAlertTask(t));
      });
      showToast(
        hasAnyInPlanner
          ? 'Todos os cards do Planner do Coach já estão sincronizados na Agenda!'
          : 'Arraste tarefas para os dias da semana no Coach IA para importá-las aqui.',
        'info'
      );
      return;
    }

    persistAgenda([...syncedExistingAgenda, ...imported]);
    if (imported.length > 0) {
      showToast(`${imported.length} missão(ões) do Coach IA sincronizada(s) na Agenda!`, 'success');
    } else {
      showToast(`${updatedExistingCount} bloco(s) atualizados com o status do Coach IA!`, 'success');
    }
  };

  const isEventFulfilledBySession = (ev) => {
    if (!ev) return false;
    if (ev.completed) return true;
    if (ev.manuallyUnchecked) return false;

    const directMatch = studySessions.some(
      (s) =>
        s &&
        ((s.agendaEventId && String(s.agendaEventId) === String(ev.id)) ||
          (s.fulfilledAgendaEventId && String(s.fulfilledAgendaEventId) === String(ev.id)))
    );
    if (directMatch) return true;

    const matchesEvSubject = (s) => {
      if (!s) return false;
      if (getDateKey(s.startTime || s.date || s.createdAt) !== ev.date) return false;
      if (s.agendaEventId || s.fulfilledAgendaEventId) return false;
      if (ev.categoryId && s.categoryId && String(ev.categoryId) === String(s.categoryId)) return true;
      return Boolean(ev.subject && (s.subject || s.categoryName) && isSubjectMatch(ev.subject, s.subject || s.categoryName));
    };

    const unlinkedSessionsCount = studySessions.filter(matchesEvSubject).length;
    if (unlinkedSessionsCount === 0) return false;

    const sameDaySameSubjEvents = agenda.filter((other) => {
      if (!other || other.date !== ev.date) return false;
      if (ev.categoryId && other.categoryId && String(ev.categoryId) === String(other.categoryId)) return true;
      return Boolean(ev.subject && other.subject && isSubjectMatch(ev.subject, other.subject));
    });
    const alreadyCompletedCount = sameDaySameSubjEvents.filter((other) => other.completed).length;
    if (alreadyCompletedCount >= unlinkedSessionsCount) return false;

    const pendingPeers = sameDaySameSubjEvents.filter((other) => !other.completed && !other.manuallyUnchecked);
    const myRank = pendingPeers.findIndex((other) => other.id === ev.id);
    return myRank !== -1 && myRank < (unlinkedSessionsCount - alreadyCompletedCount);
  };

  const handleToggleEventCompleted = (eventId) => {
    const nowIso = new Date().toISOString();
    let toggledTarget = null;
    let toggledNextState = false;
    const next = agenda.map((ev) => {
      if (!ev || ev.id !== eventId) return ev;
      const currentlyDone = isEventFulfilledBySession(ev);
      const nextCompleted = !currentlyDone;
      toggledTarget = ev;
      toggledNextState = nextCompleted;
      const updated = {
        ...ev,
        completed: nextCompleted,
        completedAt: nextCompleted ? nowIso : null,
        manuallyUnchecked: !nextCompleted,
      };
      if (!nextCompleted) {
        delete updated.autoCompletedBySession;
        delete updated.fulfilledBySessionId;
      }
      return updated;
    });

    setData((contest) => {
      const updatedContest = { ...contest, agenda: next };
      if (toggledTarget?.coachSynced && contest?.coachPlanner && typeof contest.coachPlanner === 'object') {
        const nextPlanner = { ...contest.coachPlanner };
        Object.keys(nextPlanner).forEach((dayKey) => {
          const dayList = Array.isArray(nextPlanner[dayKey]) ? nextPlanner[dayKey] : null;
          if (!dayList) return;
          nextPlanner[dayKey] = dayList.map((ct) => {
            if (!ct) return ct;
            const matchById = toggledTarget.coachPlannerTaskId && ct.id && String(ct.id) === String(toggledTarget.coachPlannerTaskId);
            const matchByTaskId = toggledTarget.taskId && ct.sourceTaskId && String(ct.sourceTaskId) === String(toggledTarget.taskId);
            if (!matchById && !matchByTaskId) return ct;
            return {
              ...ct,
              completed: toggledNextState,
              completedAt: toggledNextState ? nowIso : null,
              updatedAt: nowIso,
            };
          });
        });
        updatedContest.coachPlanner = nextPlanner;
      }
      return updatedContest;
    });
  };

  const handleStartAgendaPomodoro = (ev) => {
    if (!ev) return;
    const matchedCat = categories.find((c) =>
      c && (
        (ev.categoryId && String(c.id) === String(ev.categoryId)) ||
        (ev.subject && isSubjectMatch(ev.subject, c.name))
      )
    );
    const catTasks = matchedCat
      ? (Array.isArray(matchedCat.tasks) ? matchedCat.tasks : Object.values(matchedCat.tasks || {})).filter(Boolean)
      : [];
    const normTitle = normalize(ev.title || '');
    const normCatName = normalize(matchedCat?.name || ev.subject || '');
    const matchedTask = catTasks.find((t) => {
      if (ev.taskId && t.id && String(t.id) === String(ev.taskId)) return true;
      if (!normTitle || normTitle === normCatName) return false;
      const tNorm = normalize(t.title || t.text || '');
      return Boolean(tNorm && (tNorm === normTitle || tNorm.includes(normTitle)));
    }) || null;

    if (typeof startPomodoroSession === 'function') {
      const nextSubject = {
        categoryId: matchedCat?.id || ev.categoryId || 'geral',
        taskId: matchedTask?.id || ev.taskId || `agenda_block_${ev.id}`,
        category: matchedCat?.name || ev.subject || 'Geral',
        task: matchedTask ? (matchedTask.title || matchedTask.text) : (ev.title || 'Bloco da Agenda'),
        priority: matchedTask?.priority || 'high',
        agendaEventId: ev.id,
        isAgendaOnlyBlock: !matchedTask,
        source: 'agenda',
      };
      const currentPomodoro = useAppStore.getState().appState?.pomodoro;
      if (isSubjectAlreadyActiveInPomodoro(currentPomodoro, nextSubject, matchedCat, matchedTask)) {
        navigate('/pomodoro');
        return;
      }
      startPomodoroSession(nextSubject);
      showToast(`Iniciando bloco da Agenda: ${ev.title}`, 'success');
      navigate('/pomodoro');
    }
  };

  const getTodayAlignedDate = () => {
    const key = getDateKey(new Date());
    return (key && parseNoonLocal(key)) || new Date();
  };

  const [currentMonth, setCurrentMonth] = useState(getTodayAlignedDate);
  const [selectedDate, setSelectedDate] = useState(getTodayAlignedDate);
  const [showAdd, setShowAdd] = useState(false);

  // Form
  const [form, setForm] = useState({
    title: '',
    subject: '',
    duration: 60,
    notes: '',
    time: '09:00'
  });

  const persistAgenda = (next, removedIds = []) => {
    const nowIso = new Date().toISOString();
    setData((contest) => {
      if (!removedIds.length) {
        return { ...contest, agenda: next };
      }
      const removedSet = new Set(removedIds.map(String));
      const prevDeleted = Array.isArray(contest?.deletedAgendaIds) ? contest.deletedAgendaIds : [];
      const nextDeleted = [
        ...prevDeleted.filter((e) => e && !removedSet.has(String(e.id))),
        ...removedIds.map((id) => ({ id, deletedAt: nowIso })),
      ].slice(-200);
      return {
        ...contest,
        agenda: next,
        deletedAgendaIds: nextDeleted,
      };
    });
  };

  // Month grid days
  const calendarDays = useMemo(() => {
    const start = startOfMonth(currentMonth);
    const end = endOfMonth(currentMonth);
    const days = eachDayOfInterval({ start, end });
    const padding = start.getDay();
    const prefix = Array.from({ length: padding }).fill(null);
    return [...prefix, ...days];
  }, [currentMonth]);

  const selectedDateStr = format(selectedDate, 'yyyy-MM-dd');
  const todayStr = getDateKey(new Date()) || format(new Date(), 'yyyy-MM-dd');

  const eventsForSelected = useMemo(() => {
    return agenda
      .filter(e => e && e.date === selectedDateStr)
      .sort((a, b) => (a.time || '').localeCompare(b.time || ''));
  }, [agenda, selectedDateStr]);

  const upcomingEvents = useMemo(() => {
    return agenda
      .filter(e => e && e.date && e.date >= todayStr)
      .sort((a, b) => (a.date || '').localeCompare(b.date || '') || (a.time || '').localeCompare(b.time || ''))
      .slice(0, 6);
  }, [agenda, todayStr]);

  // Quick stats
  const totalPlannedMinutes = useMemo(() => {
    return agenda.reduce((acc, ev) => acc + Math.max(1, Math.round(Number(ev.duration) || 60)), 0);
  }, [agenda]);

  function changeMonth(delta) {
    setCurrentMonth(m => delta > 0 ? addMonths(m, 1) : subMonths(m, 1));
  }

  function selectDay(day) {
    setSelectedDate(day);
  }

  function openAddForSelected() {
    setForm({
      title: '',
      subject: categories[0]?.name || 'Geral',
      duration: 60,
      notes: '',
      time: '09:00'
    });
    setShowAdd(true);
  }

  const addEvent = () => {
    if (!form.title.trim()) {
      showToast('Título do bloco obrigatório', 'error');
      return;
    }
    const newEvent = {
      id: generateId('agenda'),
      date: selectedDateStr,
      time: form.time,
      title: form.title.trim(),
      subject: form.subject,
      duration: Math.max(1, Math.round(Number(form.duration) || 60)),
      notes: form.notes.trim(),
      createdAt: new Date().toISOString()
    };
    const next = [...agenda, newEvent];
    persistAgenda(next);
    setShowAdd(false);
    showToast('Bloco de estudo adicionado à agenda!', 'success');
  };

  const deleteEvent = (id) => {
    const ev = agenda.find(e => e.id === id);
    if (ev) setEventToDelete(ev);
  };

  const handleConfirmDeleteEvent = () => {
    if (!eventToDelete) return;
    const deletedSnapshot = { ...eventToDelete };
    const deletedId = eventToDelete.id;
    const nowIso = new Date().toISOString();
    useAppStore.getState().archiveToTrash?.({
      type: 'agenda_event',
      contestId: activeId,
      data: deletedSnapshot,
    });
    setData(contest => {
      const currentAgenda = (Array.isArray(contest?.agenda) ? contest.agenda : Object.values(contest?.agenda || {})).filter(Boolean);
      const prevDeleted = Array.isArray(contest?.deletedAgendaIds) ? contest.deletedAgendaIds : [];
      return {
        ...contest,
        agenda: currentAgenda.filter(e => e.id !== deletedId),
        deletedAgendaIds: [
          ...prevDeleted.filter(e => e && e.id !== deletedId),
          { id: deletedId, deletedAt: nowIso }
        ].slice(-100)
      };
    });
    showToast('Bloco movido para a Lixeira', 'info');
    setEventToDelete(null);
  };

  // Calendar day with event dot count
  const getEventsOnDay = (day) => {
    const dstr = format(day, 'yyyy-MM-dd');
    return agenda.filter(ev => ev.date === dstr).length;
  };

  const weekDays = ['D', 'S', 'T', 'Q', 'Q', 'S', 'S'];

  return (
    <PageErrorBoundary pageName="Agenda">
      <div className="animate-fade-in pb-12">
        {/* Header */}
        <div className="flex flex-col sm:flex-row items-start sm:items-end gap-4 justify-between mb-8">
          <div>
            <div className="flex items-center gap-3">
              <Calendar className="text-teal-400" size={28} />
              <h1 className="tool-header">Agenda de Estudos</h1>
            </div>
            <p className="text-sm text-slate-400 mt-1.5">Planeje blocos focados. Mantenha consistência.</p>
          </div>

          <div className="flex flex-wrap gap-2">
            <button
              type="button"
              onClick={handleSyncFromCoachPlanner}
              className="inline-flex items-center gap-1.5 px-3.5 py-2.5 rounded-xl text-xs font-black uppercase tracking-wider bg-violet-500/15 hover:bg-violet-500/25 border border-violet-400/35 text-violet-200 transition-colors"
              title="Importa os cards alocados nos dias da semana do Kanban do Coach IA"
            >
              <BrainCircuit size={14} /> Sincronizar Coach IA
            </button>
            <button
              type="button"
              onClick={handleRebalanceRemainingWeek}
              className="inline-flex items-center gap-1.5 px-3.5 py-2.5 rounded-xl text-xs font-black uppercase tracking-wider bg-teal-500/15 hover:bg-teal-500/25 border border-teal-400/35 text-teal-200 transition-colors"
              title="Redistribui blocos pendentes nos dias restantes desta semana sem perder prioridades Markowitz + FSRS"
            >
              <RefreshCw size={14} /> Rebalancear Semana
            </button>
            <button
              type="button"
              onClick={() => setShowAutoModal(true)}
              className="inline-flex items-center gap-1.5 px-4 py-2.5 rounded-xl text-xs font-black uppercase tracking-wider bg-indigo-500/20 hover:bg-indigo-500/30 border border-indigo-400/40 text-indigo-200 transition-colors"
            >
              <Sparkles size={15} /> Grade Semanal Ótima
            </button>
            <button onClick={openAddForSelected} className="tool-btn">
              <Plus size={17} /> Adicionar Bloco
            </button>
          </div>
        </div>

        <div className="grid grid-cols-1 xl:grid-cols-12 gap-5">
          {/* Calendar */}
          <div className="xl:col-span-7 premium-card p-5">
            <div className="flex items-center justify-between mb-4 px-1">
              <button onClick={() => changeMonth(-1)} className="p-2 rounded-full hover:bg-white/5 text-slate-400 active:bg-white/10">
                <ChevronLeft size={20} />
              </button>
              <div className="text-center">
                <div className="font-extrabold text-xl tracking-tight leading-tight pb-0.5">{format(currentMonth, "MMMM 'de' yyyy", { locale: ptBR })}</div>
                <div className="text-[10px] text-slate-400 tracking-[1.5px] uppercase mt-0.5">Clique em um dia para focar</div>
              </div>
              <button onClick={() => changeMonth(1)} className="p-2 rounded-full hover:bg-white/5 text-slate-400 active:bg-white/10">
                <ChevronRight size={20} />
              </button>
            </div>

            {/* Weekday headers */}
            <div className="grid grid-cols-7 gap-1 mb-1 text-center text-xs text-slate-500 font-bold uppercase tracking-[1.5px] px-1 leading-none pt-0.5">
              {weekDays.map((d, i) => <div key={i}>{d}</div>)}
            </div>

            <div className="grid grid-cols-7 gap-1">
              {calendarDays.map((day, idx) => {
                if (!day) {
                  return <div key={`empty-${idx}`} className="aspect-square border border-transparent" />;
                }
                const eventCount = getEventsOnDay(day);
                const isSel = isSameDay(day, selectedDate);
                const isTod = isToday(day);
                return (
                  <button
                    key={idx}
                    onClick={() => selectDay(day)}
                    className={`agenda-day aspect-square flex flex-col items-center justify-center border text-sm transition-all
                    ${isSel ? 'border-teal-400 bg-teal-500/10' : 'border-white/5 hover:border-white/20'}
                    ${isTod ? 'today' : ''}`}
                  >
                    <span className={`font-semibold tabular-nums ${isSel ? 'text-teal-200' : 'text-slate-200'}`}>
                      {format(day, 'd')}
                    </span>
                    {eventCount > 0 && (
                      <div className="mt-0.5 flex gap-0.5">
                        {Array.from({ length: Math.min(eventCount, 3) }).map((_, i) => (
                          <div key={i} className="w-1 h-1 rounded-full bg-teal-400" />
                        ))}
                      </div>
                    )}
                  </button>
                );
              })}
            </div>

            <div className="text-xs mt-4 text-slate-500 px-1 flex items-center justify-between">
              <div>{agenda.length} blocos totais • {totalPlannedMinutes} minutos planejados</div>
              <button
                onClick={() => {
                  const nowAligned = getTodayAlignedDate();
                  setCurrentMonth(nowAligned);
                  setSelectedDate(nowAligned);
                }}
                className="hover:text-teal-300"
              >
                Hoje
              </button>
            </div>
          </div>

          {/* Selected day + upcoming */}
          <div className="xl:col-span-5 space-y-5">
            {/* Selected day detail */}
            <div className="premium-card p-5">
              <div className="uppercase text-teal-300 tracking-[1.5px] text-xs font-bold mb-3 flex items-center gap-2">
                <Target size={14} /> {format(selectedDate, "EEEE, dd 'de' MMMM", { locale: ptBR })}
              </div>

              {eventsForSelected.length === 0 ? (
                <div className="empty-state py-8 text-center">
                  <Clock className="mx-auto mb-3 text-teal-300/60" size={32} />
                  <div className="text-sm text-slate-400">Nenhum bloco agendado.</div>
                  <button onClick={openAddForSelected} className="mt-4 text-xs underline text-teal-400">Planejar estudo</button>
                </div>
              ) : (
                <div className="space-y-2">
                  {eventsForSelected.map(ev => {
                    const isDone = isEventFulfilledBySession(ev);
                    return (
                      <div key={ev.id} className={`agenda-event flex justify-between items-center gap-3 group ${isDone ? 'opacity-75 border-emerald-500/30 bg-emerald-950/10' : ''}`}>
                        <button
                          type="button"
                          onClick={() => handleToggleEventCompleted(ev.id)}
                          title={isDone ? 'Marcar como pendente' : 'Marcar bloco como concluído'}
                          className={`shrink-0 p-1 rounded-lg transition-colors ${isDone ? 'text-emerald-400' : 'text-slate-500 hover:text-emerald-300'}`}
                        >
                          <CheckCircle2 size={16} />
                        </button>
                        <div className="flex-1 min-w-0">
                          <div className="flex items-center gap-2 font-medium leading-tight">
                            {ev.time && <span className="font-mono text-teal-300/90 tabular-nums text-xs tracking-wider">{ev.time}</span>}
                            <span className={isDone ? 'line-through text-slate-400' : ''}>{ev.title}</span>
                          </div>
                          <div className="text-[11px] text-slate-400 mt-0.5 flex flex-wrap items-center gap-2 leading-none">
                            <span>{ev.subject}</span>
                            <span>• {ev.duration} min</span>
                            {isDone && <span className="text-[10px] font-bold text-emerald-400 uppercase">• Concluído</span>}
                          </div>
                          {ev.notes && <div className="text-xs text-slate-400 mt-0.5 line-clamp-1 leading-snug">{ev.notes}</div>}
                        </div>
                        <div className="flex items-center gap-1 shrink-0">
                          <button
                            type="button"
                            onClick={() => handleStartAgendaPomodoro(ev)}
                            title="Iniciar este bloco no Cronômetro Pomodoro"
                            className="px-2.5 py-1.5 rounded-lg bg-teal-500/15 hover:bg-teal-500/30 border border-teal-400/30 text-teal-200 text-xs font-bold inline-flex items-center gap-1 transition-colors"
                          >
                            <Play size={12} className="fill-current" /> Focar
                          </button>
                          <button onClick={() => deleteEvent(ev.id)} className="opacity-60 group-hover:opacity-100 text-rose-400 p-1.5" title="Remover bloco">
                            <Trash2 size={15} />
                          </button>
                        </div>
                      </div>
                    );
                  })}
                </div>
              )}
            </div>

            {/* Upcoming */}
            <div className="premium-card p-5">
              <div className="flex justify-between mb-3">
                <div className="micro-label">Próximos Compromissos</div>
                <div className="text-xs text-slate-500">{upcomingEvents.length} agendados</div>
              </div>
              {upcomingEvents.length === 0 && (
                <div className="text-xs text-slate-400 py-2">Sem compromissos futuros. Adicione blocos para se manter no trilho.</div>
              )}
              <div className="space-y-2">
                {upcomingEvents.map(ev => {
                  const isDone = isEventFulfilledBySession(ev);
                  return (
                    <div key={ev.id} className="flex items-center justify-between gap-2 rounded-xl bg-white/[0.025] px-3 py-2 text-sm border border-white/5">
                      <div className="min-w-0 flex-1">
                        <div className={`font-medium leading-tight truncate ${isDone ? 'line-through text-slate-400' : ''}`}>{ev.title}</div>
                        <div className="text-[11px] text-teal-300/90">
                          {(() => {
                            const parsed = ev.date ? (parseNoonLocal(ev.date) || normalizeDate(ev.date)) : null;
                            return parsed && Number.isFinite(parsed.getTime()) ? format(parsed, 'dd/MM') : '--';
                          })()}
                          {ev.time ? ` • ${ev.time}` : ''}
                          {ev.duration ? ` • ${ev.duration}min` : ''}
                          {isDone ? ' • ✓' : ''}
                        </div>
                      </div>
                      <div className="flex items-center gap-1.5 shrink-0">
                        <button
                          type="button"
                          onClick={() => handleStartAgendaPomodoro(ev)}
                          title="Iniciar no Pomodoro"
                          className="p-1.5 rounded-lg bg-teal-500/10 hover:bg-teal-500/25 text-teal-300 transition-colors"
                        >
                          <Play size={13} className="fill-current" />
                        </button>
                        <button onClick={() => deleteEvent(ev.id)} className="text-rose-400/70 hover:text-rose-400 p-1">
                          <Trash2 size={15} />
                        </button>
                      </div>
                    </div>
                  );
                })}
              </div>
            </div>
          </div>
        </div>

        {/* Add modal */}
        {showAdd && (
          <div className="fixed inset-0 bg-black/70 flex items-center justify-center p-4 z-[200]" onClick={() => setShowAdd(false)}>
            <div className="premium-card w-full max-w-md p-6" onClick={e => e.stopPropagation()}>
              <h3 className="font-extrabold text-xl mb-1 leading-tight">Novo Bloco de Estudo</h3>
              <div className="text-xs text-teal-400 mb-4">{format(selectedDate, "dd 'de' MMMM yyyy", { locale: ptBR })}</div>

              <div className="space-y-4">
                <div>
                  <label className="micro-label mb-1 block">Título / Foco</label>
                  <input value={form.title} onChange={e => setForm({ ...form, title: e.target.value })} className="w-full bg-black/40 border border-white/10 rounded-xl px-4 py-3 text-sm" placeholder="Revisão de Aritmética" />
                </div>

                <div className="grid grid-cols-2 gap-4">
                  <div>
                    <label className="micro-label mb-1 block">Disciplina</label>
                    <select value={form.subject} onChange={e => setForm({ ...form, subject: e.target.value })} className="w-full bg-black/40 border border-white/10 rounded-xl px-4 py-3 text-sm">
                      {categories.map(c => (
                        <option key={c.id} value={c.name}>{c.name}</option>
                      ))}
                      <option value="Geral">Geral</option>
                    </select>
                  </div>
                  <div>
                    <label className="micro-label mb-1 block">Duração (min)</label>
                    <input type="number" min="1" value={form.duration} onChange={e => setForm({ ...form, duration: e.target.value })} className="w-full bg-black/40 border border-white/10 rounded-xl px-4 py-3 text-sm" />
                  </div>
                </div>

                <div className="grid grid-cols-2 gap-4">
                  <div>
                    <label className="micro-label mb-1 block">Horário</label>
                    <input type="time" value={form.time} onChange={e => setForm({ ...form, time: e.target.value })} className="w-full bg-black/40 border border-white/10 rounded-xl px-4 py-3 text-sm font-mono" />
                  </div>
                  <div>
                    <label className="micro-label mb-1 block">Notas (opcional)</label>
                    <input value={form.notes} onChange={e => setForm({ ...form, notes: e.target.value })} placeholder="Revisar erros do último simulado" className="w-full bg-black/40 border border-white/10 rounded-xl px-4 py-3 text-sm" />
                  </div>
                </div>
              </div>

              <div className="flex gap-3 mt-7">
                <button onClick={() => setShowAdd(false)} className="tool-btn secondary flex-1">Cancelar</button>
                <button onClick={addEvent} className="tool-btn flex-1">Agendar Bloco</button>
              </div>
            </div>
          </div>
        )}

        {showAutoModal && (
          <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/75 backdrop-blur-md p-4" onClick={() => setShowAutoModal(false)}>
            <div className="glass max-w-xl w-full p-6 rounded-3xl border border-indigo-400/25 shadow-2xl space-y-5 max-h-[85vh] overflow-y-auto" onClick={(e) => e.stopPropagation()}>
              <div className="flex items-center justify-between gap-2">
                <div>
                  <h2 className="text-lg font-black text-white flex items-center gap-2">
                    <Sparkles size={18} className="text-indigo-400" />
                    Gerador de Grade Semanal Ótima
                  </h2>
                  <p className="text-xs text-slate-400 mt-0.5">
                    Combina alocação Markowitz + seu cronotipo circadiano + retenção FSRS + pré-requisitos
                  </p>
                </div>
                <button type="button" onClick={() => setShowAutoModal(false)} className="text-slate-400 hover:text-white text-sm font-bold px-2">✕</button>
              </div>

              <div>
                <p className="text-[11px] font-bold uppercase tracking-wider text-slate-400 mb-2">Horas disponíveis por dia (Dom → Sáb)</p>
                <div className="grid grid-cols-7 gap-2">
                  {['Dom', 'Seg', 'Ter', 'Qua', 'Qui', 'Sex', 'Sáb'].map((lbl, idx) => (
                    <label key={lbl} className="flex flex-col items-center gap-1 text-[10px] text-slate-400">
                      <span className="font-bold">{lbl}</span>
                      <input
                        type="number"
                        min={0}
                        max={8}
                        value={dailyHours[idx]}
                        onChange={(e) => {
                          const v = Math.max(0, Math.min(8, Number(e.target.value) || 0));
                          setDailyHours((prev) => prev.map((h, i) => (i === idx ? v : h)));
                        }}
                        className="w-full text-center bg-slate-900 border border-white/10 rounded-lg py-1.5 text-white font-mono text-xs"
                      />
                    </label>
                  ))}
                </div>
              </div>

              {optimalPreview?.summary && (
                <div className="rounded-2xl border border-white/10 bg-slate-950/60 p-3.5 text-xs space-y-2">
                  <div className="flex flex-wrap gap-3 font-mono text-indigo-300">
                    <span>{optimalPreview.summary.totalBlocks} blocos (60m)</span>
                    <span>• Início nobre: {optimalPreview.summary.peakStartHour}</span>
                    <span>• Cronotipo: {optimalPreview.summary.chronotype}</span>
                  </div>
                  <div className="max-h-44 overflow-y-auto space-y-1.5 pt-1">
                    {optimalPreview.events.slice(0, 12).map((ev) => (
                      <div key={ev.id} className="flex items-center justify-between gap-2 text-[11px] bg-slate-900/70 rounded-lg px-2.5 py-1.5">
                        <span className="font-mono text-slate-400 shrink-0">{ev.date.slice(5)} {ev.time}</span>
                        <span className="text-slate-200 font-semibold truncate flex-1">{ev.title}</span>
                      </div>
                    ))}
                    {optimalPreview.events.length > 12 && (
                      <p className="text-[10px] text-slate-500 text-center">+{optimalPreview.events.length - 12} bloco(s) adicionais</p>
                    )}
                  </div>
                </div>
              )}

              <div className="flex gap-3">
                <button type="button" onClick={() => setShowAutoModal(false)} className="tool-btn secondary flex-1">Cancelar</button>
                <button type="button" onClick={applyOptimalSchedule} className="tool-btn flex-1">Aplicar na Agenda</button>
              </div>
            </div>
          </div>
        )}

        <ConfirmModal
          isOpen={!!eventToDelete}
          onClose={() => setEventToDelete(null)}
          onConfirm={handleConfirmDeleteEvent}
          title="Remover Compromisso"
          message={`Deseja remover o compromisso "${eventToDelete?.title || ''}" da sua agenda?`}
          confirmText="Remover"
          type="danger"
          icon={Trash2}
        />
      </div>
    </PageErrorBoundary>
  );
}
